// Saves report documents built from the demo orders to app/test/fixtures/report_doc.json.
// The Dart report builder must produce exactly these. Run after a deliberate change:
//   node tools/report-preview/gen-fixture.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { reportDocument } from '../rules-check/report-doc.mjs';
import { reportWorkbook, dataWorkbook } from '../rules-check/export-doc.mjs';
import { HijriCalendar } from '../rules-check/hijri.mjs';

const root = new URL('../../', import.meta.url);
const json = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const rules = json('app/assets/rules/rules.json');
const en = json('app/assets/i18n/en.json');
const ar = json('app/assets/i18n/ar.json');
const hijri = new HijriCalendar(json('app/assets/calendar/umalqura.json'));
const demo = json('app/assets/demo/demo_orders.json');

const cases = [
  { kind: 'daily', date: demo.today, today: demo.today, lang: 'en', preparedBy: 'Engr Najim', generatedAt: `${demo.today} 20:55` },
  { kind: 'daily', date: demo.today, today: demo.today, lang: 'ar', preparedBy: 'م. نجم', generatedAt: `${demo.today} 20:55` },
  { kind: 'weekly', date: '2026-10-08', today: demo.today, lang: 'en', preparedBy: 'Engr Najim', generatedAt: `${demo.today} 09:10` },
  { kind: 'weekly', date: demo.today, today: demo.today, lang: 'ar', preparedBy: 'م. نجم', generatedAt: `${demo.today} 09:10` },
  { kind: 'daily', date: '2026-10-04', today: demo.today, lang: 'en', preparedBy: 'Engr Najim', generatedAt: `${demo.today} 09:10` },
  { kind: 'monthly', date: '2026-09-15', today: demo.today, lang: 'ar', preparedBy: 'م. نجم', generatedAt: null },
].map((c) => ({ ...c, doc: reportDocument(rules, demo.orders, c.kind, c.date, c.today, { lang: c.lang, text: c.lang === 'ar' ? ar : en, english: en, hijri, preparedBy: c.preparedBy, generatedAt: c.generatedAt }) }));

writeFileSync(new URL('app/test/fixtures/report_doc.json', root), JSON.stringify({ note: 'Generated by tools/report-preview/gen-fixture.mjs from the demo orders. The reference figures underneath are hand-checked in insights.json.', cases }, null, 1) + '\n');
console.log(`saved ${cases.length} report cases`);

// Excel workbooks: the Dart builders must produce exactly these.
const opt = (lang) => ({ lang, text: lang === 'ar' ? ar : en, english: en, hijri, preparedBy: lang === 'ar' ? 'م. نجم' : 'Engr Najim', generatedAt: `${demo.today} 20:55` });
const exportCases = {
  note: 'Generated by tools/report-preview/gen-fixture.mjs from the demo orders.',
  report: [
    { kind: 'daily', date: demo.today, lang: 'en' },
    { kind: 'monthly', date: '2026-09-15', lang: 'ar' },
  ].map((c) => ({ ...c, today: demo.today, preparedBy: opt(c.lang).preparedBy, generatedAt: opt(c.lang).generatedAt, workbook: reportWorkbook(rules, demo.orders, c.kind, c.date, demo.today, opt(c.lang)) })),
  data: { today: demo.today, generatedAt: `${demo.today} 20:55`, workbook: dataWorkbook(rules, demo.orders, demo.today, `${demo.today} 20:55`) },
};
writeFileSync(new URL('app/test/fixtures/export_doc.json', root), JSON.stringify(exportCases) + '\n');
console.log('saved export cases');
